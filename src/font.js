export const FONT = {};
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split('|');
  FONT[ch] = { w: rows[0].length, rows };
}

export const LINE_H = 9;

export function textWidth(str) {
  let w = 0;
  for (const ch of str.toUpperCase()) w += (FONT[ch] || FONT['?']).w + 1;
  return Math.max(0, w - 1);
}

// Split text into lines that fit in `max` pixels.
export function wrap(str, max) {
  const lines = [];
  let line = '';
  for (const word of str.split(' ')) {
    const t = line ? line + ' ' + word : word;
    if (textWidth(t) <= max || !line) line = t;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}
